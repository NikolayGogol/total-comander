import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const pkgPath = path.join(__dirname, '../package.json')
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
const outPath = path.join(__dirname, '../src/buildInfo.ts')

const now = new Date()
const yyyy = now.getFullYear()
const mm = String(now.getMonth() + 1).padStart(2, '0')
const dd = String(now.getDate()).padStart(2, '0')
const hh = String(now.getHours()).padStart(2, '0')
const min = String(now.getMinutes()).padStart(2, '0')
const ss = String(now.getSeconds()).padStart(2, '0')

const datePrefix = `${yyyy}.${mm}.${dd}`
let buildIndex = 1

if (fs.existsSync(outPath)) {
  try {
    const existing = fs.readFileSync(outPath, 'utf8')
    const match = existing.match(/buildNumber:\s*['"](\d{4}\.\d{2}\.\d{2})\.(\d+)['"]/)
    if (match) {
      const prevDate = match[1]
      const prevIndex = parseInt(match[2], 10)
      if (prevDate === datePrefix && !isNaN(prevIndex)) {
        buildIndex = prevIndex + 1
      }
    }
  } catch {}
}

const buildNumber = `${datePrefix}.${buildIndex}`
const buildDate = `${yyyy}-${mm}-${dd} ${hh}:${min}:${ss}`

const shouldBump =
  process.argv.includes('--bump') ||
  (process.env.npm_lifecycle_event &&
    process.env.npm_lifecycle_event.startsWith('build'))

if (shouldBump) {
  const semverParts = (pkg.version || '1.0.0').split('.').map((n) => parseInt(n, 10))
  if (semverParts.length >= 3 && !semverParts.some(isNaN)) {
    semverParts[2] += 1
    pkg.version = semverParts.join('.')
  } else {
    pkg.version = '1.0.1'
  }

  if (!pkg.build) {
    pkg.build = {}
  }
  pkg.build.buildVersion = buildNumber

  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8')
  console.log(`[build-info] Bumped package.json version to v${pkg.version} (build ${buildNumber})`)
}

const currentVersion = pkg.version || '1.0.0'

const content = `// Auto-generated by scripts/update-build-info.mjs. Do not edit manually.
export interface BuildInfoData {
  version: string
  buildNumber: string
  buildDate: string
  platform: string
}

export const BUILD_INFO: BuildInfoData = {
  version: '${currentVersion}',
  buildNumber: '${buildNumber}',
  buildDate: '${buildDate}',
  platform: 'macOS',
}
`

fs.writeFileSync(outPath, content, 'utf8')
console.log(
  `[build-info] Generated buildInfo.ts: v${currentVersion} (${buildNumber}) [build ${buildIndex} today]`
)
